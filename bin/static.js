import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs'
import { spawn } from 'node:child_process'
import { dirname, isAbsolute, join, relative } from 'node:path'

/**
 * Written into every generated site. `--out` is wiped and rebuilt on each run,
 * so this marks a directory as ours to overwrite: without it (and without
 * `--force`), a non-empty output directory is left alone.
 */
export const SITE_MARKER = '.pulumi-package-docs-site'

/** The intermediate Vite output directory (see `build.outDir` in vite.config.ts). */
const STATIC_BUILD_DIR = 'dist-static'

/**
 * Normalizes a `--base` value to the form Vite and the router want: a path
 * with both a leading and a trailing slash ("/repo" -> "/repo/"), or "/" for a
 * site served from a domain root.
 */
export function normalizeBase(base) {
  const trimmed = (base ?? '').trim()
  if (trimmed === '' || trimmed === '/') return '/'
  return `/${trimmed.replace(/^\/+/, '').replace(/\/+$/, '')}/`
}

/**
 * Drops the leftovers of a client bundle the static pages never load.
 *
 * Static pages are rendered without the hydration script (see
 * `src/lib/static-docs.ts`), but the framework still emits `modulepreload`
 * hints for the client chunks and, after `</html>`, the serialized loader data
 * hydration would have used. Nothing reads either one here, so removing them
 * saves every page a round of pointless downloads and roughly halves its size.
 * Both patterns are best-effort: if a future version emits something else, the
 * pages are merely bigger, never broken.
 */
export function stripClientPayload(html) {
  return html
    .replace(/<link\s+rel="modulepreload"[^>]*>/g, '')
    .replace(/<\/html>[\s\S]*$/, '</html>')
}

function walk(dir) {
  const files = []
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry)
    if (statSync(full).isDirectory()) files.push(...walk(full))
    else files.push(full)
  }
  return files
}

/** True when `child` is `parent` itself or sits inside it. */
function contains(parent, child) {
  const rel = relative(parent, child)
  return rel === '' || (!rel.startsWith('..') && !isAbsolute(rel))
}

function isReusableOutputDir(out) {
  if (!existsSync(out)) return true
  if (!statSync(out).isDirectory()) return false
  const entries = readdirSync(out)
  return entries.length === 0 || entries.includes(SITE_MARKER)
}

/**
 * Copies a prerendered client build into the output directory, rewriting HTML
 * on the way, and adds the files a Pages host expects.
 */
export function collectSite(clientDir, out) {
  rmSync(out, { recursive: true, force: true })
  mkdirSync(out, { recursive: true })

  const files = walk(clientDir)
  const htmlFiles = files.filter((file) => file.endsWith('.html'))
  const assetFiles = files.filter((file) => !file.endsWith('.html'))

  let rendered = ''
  for (const file of htmlFiles) {
    const html = stripClientPayload(readFileSync(file, 'utf-8'))
    const target = join(out, relative(clientDir, file))
    mkdirSync(dirname(target), { recursive: true })
    writeFileSync(target, html)
    rendered += html
  }

  for (const file of assetFiles) {
    const path = relative(clientDir, file).split('\\').join('/')
    // The client bundle is built but never loaded by a static page, so its
    // chunks are dead weight in the published site. Scripts are the only
    // asset a page can pull in without the HTML naming them (stylesheets are
    // linked, and this app's CSS references no other files), so checking the
    // rendered HTML is enough to know a chunk is unused.
    if (/\.(js|mjs|map)$/.test(path) && !rendered.includes(path)) continue
    const target = join(out, path)
    mkdirSync(dirname(target), { recursive: true })
    writeFileSync(target, readFileSync(file))
  }

  const pages = htmlFiles.length

  // GitHub Pages runs the output through Jekyll unless this file is present,
  // which would drop anything starting with "_" or ".".
  writeFileSync(join(out, '.nojekyll'), '')
  writeFileSync(
    join(out, SITE_MARKER),
    'Generated by `pulumi-package-docs static`. This directory is rebuilt from scratch on every run.\n',
  )

  return pages
}

function runViteBuild({ packageRoot, viteBin, dir, base }) {
  return new Promise((resolve, reject) => {
    const child = spawn(process.execPath, [viteBin, 'build'], {
      cwd: packageRoot,
      stdio: 'inherit',
      env: {
        ...process.env,
        PULUMI_LOCAL_DOCS_DIR: dir,
        VITE_STATIC_DOCS: 'true',
        PULUMI_DOCS_BASE: base,
      },
    })
    child.on('error', reject)
    child.on('exit', (code) =>
      code === 0
        ? resolve()
        : reject(new Error(`vite build exited with code ${code}`)),
    )
  })
}

/**
 * Builds a self-contained static site for the Pulumi project in `dir`: every
 * provider, resource and function page prerendered to HTML, ready to publish
 * to GitHub Pages, GitLab Pages, or any other static host.
 */
export async function buildStaticSite({
  packageRoot,
  viteBin,
  dir,
  out,
  base,
  force,
}) {
  const normalizedBase = normalizeBase(base)

  // The output directory is wiped and rebuilt on every run, so it must never
  // be the Pulumi project itself (`--out .`) or anything above it — not even
  // with --force.
  if (contains(out, dir)) {
    throw new Error(
      `Refusing to generate into ${out}: it holds the Pulumi project being documented, and --out is erased on each run.`,
    )
  }

  if (!force && !isReusableOutputDir(out)) {
    throw new Error(
      `Refusing to overwrite ${out}: it isn't empty and wasn't generated by pulumi-package-docs.\n` +
        'Pass --out <path> to write somewhere else, or --force to overwrite it anyway.',
    )
  }

  console.log(`Generating static docs for: ${dir}`)
  if (normalizedBase !== '/') console.log(`Base path: ${normalizedBase}`)

  await runViteBuild({ packageRoot, viteBin, dir, base: normalizedBase })

  const clientDir = join(packageRoot, STATIC_BUILD_DIR, 'client')
  if (!existsSync(clientDir)) {
    throw new Error(
      `The build produced no client output at ${clientDir}; cannot generate a static site.`,
    )
  }

  const pages = collectSite(clientDir, out)
  console.log(`\nWrote ${pages} pages to ${out}`)
  if (normalizedBase === '/') {
    console.log(
      'Preview it locally with: npx serve <out>  (or any static file server)',
    )
  } else {
    console.log(
      `The site expects to be served from ${normalizedBase} — links and assets are prefixed with it.`,
    )
  }
}
